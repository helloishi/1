def total(scores, penalty):
    s = dict(zip(WEIGHTS, scores))
    return round(sum(WEIGHTS[k] * s[k] for k in WEIGHTS) - penalty, 2)


def main():
    rows = []
    for (iid, track, title, pitch, pain, gap, auth, data, horizon, aud, scores, pen, status) in IDEAS:
        rows.append({
            "id": iid, "track": track, "track_ru": TRACKS[track], "title": title, "pitch": pitch,
            "pain_evidence": pain, "gap": gap, "authority": auth, "data": data, "horizon": horizon,
            "audiences": aud, "scores": dict(zip(WEIGHTS, scores)), "penalty": pen,
            "total": total(scores, pen), "status": status,
        })
    rows.sort(key=lambda r: (-r["total"], r["id"]))
    for i, r in enumerate(rows, 1):
        r["rank"] = i
    here = Path(__file__).parent
    (here / "idea-bank.json").write_text(json.dumps({"weights": WEIGHTS, "tracks": TRACKS, "ideas": rows}, ensure_ascii=False, indent=1))

    status_ru = {"built": "собран", "next": "следующий спринт", "backlog": "бэклог"}
    lines = ["# Банк идей London Civic Hack 2026", "",
             f"{len(rows)} идей в 6 треках. Итог = 0,25·польза + 0,20·власти + 0,20·разрыв + 0,15·реализуемость + 0,10·бесплатность и приватность + 0,10·охват − штраф (рубрика: `00-brief.md`). Пересчитать: `python3 build_idea_bank.py`.", "",
             "| # | Идея | Трек | Итог | Польза | Власти | Разрыв | Реализ. | Беспл. | Охват | Штраф | Статус |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        s = r["scores"]
        lines.append(f"| {r['rank']} | **{r['title']}** ({r['id']}) | {r['track_ru']} | **{r['total']:.2f}** | {s['citizen']} | {s['gov']} | {s['gap']} | {s['feasible']} | {s['free']} | {s['reach']} | {('−' + str(r['penalty'])) if r['penalty'] else ''} | {status_ru[r['status']]} |")
    lines += ["", "## Карточки", ""]
    for r in rows:
        lines += [f"### {r['rank']}. {r['title']} · {r['track_ru']} · {r['total']:.2f}", "",
                  f"{r['pitch']}", "",
                  f"- **Боль и доказательства:** {r['pain_evidence']}",
                  f"- **Что есть и чего не хватает:** {r['gap']}",
                  f"- **Кому из властей ценно:** {r['authority']}",
                  f"- **Данные:** {r['data']}",
                  f"- **Аудитории:** {', '.join(AUD[a] for a in r['audiences'])} · **горизонт:** {r['horizon']} · **статус:** {status_ru[r['status']]}", ""]
    (here / "idea-bank.md").write_text("\n".join(lines))
    print(f"{len(rows)} ideas written")
    for r in rows[:15]:
        print(f"{r['rank']:>2}. {r['total']:.2f}  {r['title']:<32} {r['track']:<7} {r['status']}")


